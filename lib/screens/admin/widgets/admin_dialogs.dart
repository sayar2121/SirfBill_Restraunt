  final _tenantId = 'AUTOGENERATED-TENANT';
  String? _logoUrl;
  bool _isUploadingLogo = false;

  // SECTION 02: ADDRESS & CONTACT
  final _addressLine1Ctrl = TextEditingController();
  final _addressLine2Ctrl = TextEditingController();
  final _cityCtrl = TextEditingController(text: 'Kolkata');
  final _stateCtrl = TextEditingController(text: 'West Bengal');
  final _pinCodeCtrl = TextEditingController();
  final _countryCtrl = TextEditingController(text: 'India');
  final _phoneCtrl = TextEditingController();
  final _emailCtrl = TextEditingController();
  final _latLngCtrl = TextEditingController();

  // SECTION 03: OPERATING SETTINGS
  String _timeZone = 'Asia/Kolkata (IST +5:30)';
  String _currency = 'INR (₹)';
