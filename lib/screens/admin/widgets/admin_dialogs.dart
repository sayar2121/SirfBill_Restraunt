  Future<void> _pickAndUploadLogo() async {
    try {
      final result = await FilePicker.platform.pickFiles(
        type: FileType.custom,
        allowedExtensions: ['jpg', 'jpeg', 'png', 'webp'],
        withData: true,
      );

      if (result == null || result.files.isEmpty) return;

      final file = result.files.first;
      final fileBytes = file.bytes;

      if (fileBytes == null) {
        _showWarning('Unable to read selected logo file bytes.');
        return;
      }

      setState(() => _isUploadingLogo = true);

      final uploadedUrl = await ShopSettingsService.uploadLogo(fileBytes, file.name);

      if (mounted) {
        setState(() {
          _logoUrl = uploadedUrl;
          _isUploadingLogo = false;
        });
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Branch logo uploaded successfully! Remember to save profile.'),
            backgroundColor: Color(0xFF10B981),
            behavior: SnackBarBehavior.floating,
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isUploadingLogo = false);
        _showWarning('Failed to upload logo: $e');
      }
    }
  }

  Future<void> _fetchStaffMembers() async {
    try {
      final staff = await AdminStaffService.getStaffUsers();
      if (mounted) {
        setState(() {
          _availableStaff = staff;
          _loadingStaff = false;
        });
      }
    } catch (_) {
      if (mounted) setState(() => _loadingStaff = false);
    }
  }

