  final _closingTimeCtrl = TextEditingController(text: '11:00 PM');
  String _weeklyClosing = 'None (Open 7 Days)';
  bool _enableDineIn = true;
  bool _enableTakeaway = true;
  bool _enableDelivery = true;
  bool _isPrimary = false;

  // SECTION 04: BILLING & TAX
  String _gstStatus = 'Registered (Regular)';
  final _gstinCtrl = TextEditingController();
  final _invoicePrefixCtrl = TextEditingController(text: 'SB');
  final _billNumberFormatCtrl = TextEditingController(text: '{PREFIX}-{YYYY}-{0001}');
