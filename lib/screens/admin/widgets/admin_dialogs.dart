      _closingTimeCtrl.text = b.closingTime ?? extra['closing_time'] ?? raw['closing_time'] ?? _closingTimeCtrl.text;
      _weeklyClosing = extra['weekly_closing'] ?? raw['weekly_closing'] ?? _weeklyClosing;
      _enableDineIn = extra['enable_dine_in'] ?? raw['enable_dine_in'] ?? _enableDineIn;
      _enableTakeaway = extra['enable_takeaway'] ?? raw['enable_takeaway'] ?? _enableTakeaway;
      _enableDelivery = extra['enable_delivery'] ?? raw['enable_delivery'] ?? _enableDelivery;

      // Section 04: Billing & Tax
      _gstStatus = extra['gst_status'] ?? raw['gst_status'] ?? _gstStatus;
      _gstinCtrl.text = b.gstin ?? extra['gstin'] ?? raw['gstin'] ?? '';
      _invoicePrefixCtrl.text = b.invoicePrefix ?? extra['invoice_prefix'] ?? raw['invoice_prefix'] ?? _invoicePrefixCtrl.text;
      _billNumberFormatCtrl.text = extra['bill_number_format'] ?? raw['bill_number_format'] ?? _billNumberFormatCtrl.text;
      if (b.taxRate != null) {
        _taxRateCtrl.text = b.taxRate.toString();
      } else if (extra['tax_rate'] != null || raw['tax_rate'] != null) {
        _taxRateCtrl.text = (extra['tax_rate'] ?? raw['tax_rate']).toString();
      }
      _rounding = extra['rounding'] ?? raw['rounding'] ?? _rounding;
      _receiptFooterCtrl.text = extra['receipt_footer'] ?? raw['receipt_footer'] ?? _receiptFooterCtrl.text;
      _fssaiCtrl.text = b.fssai ?? extra['fssai'] ?? raw['fssai'] ?? '';
      _upiIdCtrl.text = extra['upi_id'] ?? raw['upi_id'] ?? '';
      _bankAccountNameCtrl.text = b.bankAccountName ?? extra['bank_account_name'] ?? raw['bank_account_name'] ?? extra['ac_holder_name'] ?? '';
      _bankNameCtrl.text = extra['bank_name'] ?? raw['bank_name'] ?? '';
      _bankAccountCtrl.text = extra['bank_account'] ?? raw['bank_account'] ?? extra['account_number'] ?? '';
      _bankIfscCtrl.text = extra['bank_ifsc'] ?? raw['bank_ifsc'] ?? extra['ifsc_code'] ?? '';
      _bankBranchCtrl.text = extra['bank_branch'] ?? raw['bank_branch'] ?? '';

