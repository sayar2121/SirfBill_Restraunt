  Future<void> _saveOutlet() async {
    if (_nameCtrl.text.trim().isEmpty) {
      _showWarning('Please provide Outlet Name in Section 01.');
      _tabController.animateTo(0);
      return;
    }
    if (_addressLine1Ctrl.text.trim().isEmpty || _cityCtrl.text.trim().isEmpty) {
      _showWarning('Please provide Address Line 1 and City in Section 02.');
      _tabController.animateTo(1);
      return;
    }
    final rawPhone = _phoneCtrl.text.trim().replaceAll(RegExp(r'\D'), '');
    if (rawPhone.length != 10) {
      _showWarning('Please enter a valid 10-digit Outlet Phone number in Section 02.');
      _tabController.animateTo(1);
      return;
    }
    final formattedPhone = '+91 $rawPhone';

    // 15-digit / 15-character GSTIN validation
    final gstin = _gstinCtrl.text.trim().toUpperCase();
    if (_gstStatus.contains('Registered') || _gstStatus.contains('Composition')) {
      if (gstin.isEmpty) {
        _showWarning('Please provide the 15-digit GSTIN number in Section 04.');
        _tabController.animateTo(3);
        return;
      }
    }
    if (gstin.isNotEmpty) {
      final gstinRegex = RegExp(r'^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$');
      if (gstin.length != 15) {
        _showWarning('GSTIN must be exactly 15 characters long in Section 04. Current length: ${gstin.length}');
        _tabController.animateTo(3);
        return;
      } else if (!gstinRegex.hasMatch(gstin)) {
        _showWarning('Invalid GSTIN format in Section 04. Expected standard 15-character format (e.g. 19AAAAA0000A1Z5).');
        _tabController.animateTo(3);
        return;
      }
    }

    // 14-digit FSSAI validation
    final fssai = _fssaiCtrl.text.trim();
    if (fssai.isNotEmpty) {
      if (fssai.length != 14 || !RegExp(r'^[0-9]{14}$').hasMatch(fssai)) {
        _showWarning('FSSAI Licence Number must be exactly 14 numeric digits in Section 04. Current length: ${fssai.length}');
        _tabController.animateTo(3);
        return;
      }
    }

    setState(() => _isSubmitting = true);
    try {
      final formattedAddress = [
        _addressLine1Ctrl.text.trim(),
        if (_addressLine2Ctrl.text.trim().isNotEmpty) _addressLine2Ctrl.text.trim(),
        if (_stateCtrl.text.trim().isNotEmpty) _stateCtrl.text.trim(),
        if (_pinCodeCtrl.text.trim().isNotEmpty) 'PIN: ${_pinCodeCtrl.text.trim()}',
      ].join(', ');

      final extraData = <String, dynamic>{
        'outlet_type': _outletType,
        'description': _descriptionCtrl.text.trim(),
        'address_line1': _addressLine1Ctrl.text.trim(),
        'address_line2': _addressLine2Ctrl.text.trim(),
        'state': _stateCtrl.text.trim(),
        'pin_code': _pinCodeCtrl.text.trim(),
        'country': _countryCtrl.text.trim(),
        'email': _emailCtrl.text.trim(),
        'lat_lng': _latLngCtrl.text.trim(),
        'time_zone': _timeZone,
        'currency': _currency,
        'opening_time': _openingTimeCtrl.text.trim(),
        'closing_time': _closingTimeCtrl.text.trim(),
        'weekly_closing': _weeklyClosing,
        'enable_dine_in': _enableDineIn,
        'enable_takeaway': _enableTakeaway,
        'enable_delivery': _enableDelivery,
        'gst_status': _gstStatus,
        'gstin': _gstinCtrl.text.trim(),
        'invoice_prefix': _invoicePrefixCtrl.text.trim(),
        'bill_number_format': _billNumberFormatCtrl.text.trim(),
        'tax_rate': double.tryParse(_taxRateCtrl.text.trim()) ?? 5.0,
        'rounding': _rounding,
        'receipt_footer': _receiptFooterCtrl.text.trim(),
        'fssai': _fssaiCtrl.text.trim(),
        'upi_id': _upiIdCtrl.text.trim(),
        'bank_account_name': _bankAccountNameCtrl.text.trim(),
        'bank_name': _bankNameCtrl.text.trim(),
        'bank_account': _bankAccountCtrl.text.trim(),
        'bank_ifsc': _bankIfscCtrl.text.trim().toUpperCase(),
        'bank_branch': _bankBranchCtrl.text.trim(),
        'manager_id': _assignedManager,
        'assigned_staff': _assignedStaff,
        'allow_multi_outlet': _allowMultiOutletAccess,
        'max_discount_limit': double.tryParse(_maxDiscountLimitCtrl.text.trim()) ?? 20.0,
        'max_refund_limit': double.tryParse(_maxRefundLimitCtrl.text.trim()) ?? 2000.0,
        'logo_url': _logoUrl,
      };

      if (widget.existingBranch != null) {
        await ShopService.updateShop(
          id: widget.existingBranch!.id,
          name: _nameCtrl.text.trim(),
          code: _codeCtrl.text.trim().isNotEmpty ? _codeCtrl.text.trim() : widget.existingBranch!.code,
          address: formattedAddress,
          city: _cityCtrl.text.trim(),
          contactNumber: formattedPhone,
          status: _status,
          isPrimary: _isPrimary,
          extraData: extraData,
        );
      } else {
        final newShop = await ShopService.createShop(
          name: _nameCtrl.text.trim(),
          code: _codeCtrl.text.trim().isNotEmpty ? _codeCtrl.text.trim() : 'OUT-${DateTime.now().millisecondsSinceEpoch.toString().substring(8)}',
          address: formattedAddress,
          city: _cityCtrl.text.trim(),
          contactNumber: formattedPhone,
          status: _status,
          isPrimary: _isPrimary,
          extraData: extraData,
        );

        // Automatically provision station logins for POS, Kitchen, Inventory, CRM
        final cleanCode = newShop.code.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '').toLowerCase();
        final stations = [
          {'role': 'cashier', 'user': 'pos_$cleanCode@sirfbill.com', 'title': 'POS Cashier'},
          {'role': 'chef', 'user': 'kitchen_$cleanCode@sirfbill.com', 'title': 'Kitchen KDS'},
          {'role': 'manager', 'user': 'inventory_$cleanCode@sirfbill.com', 'title': 'Inventory Manager'},
          {'role': 'manager', 'user': 'crm_$cleanCode@sirfbill.com', 'title': 'Store CRM & Reports'},
        ];

        for (final station in stations) {
          try {
            await AdminStaffService.createStaffUser(
              username: station['user']!,
              password: '123456',
              name: '${newShop.name} ${station['title']}',
              role: station['role']!,
              branchId: newShop.id,
            );
          } catch (_) {
            // Silently continue if backend already provisions or stores locally
          }
        }
      }

      if (mounted) {
        Navigator.pop(context);
        widget.onSaved();
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isSubmitting = false);
        _showWarning(e.toString());
      }
    }
  }

