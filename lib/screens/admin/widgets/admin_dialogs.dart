      _descriptionCtrl.text = extra['description'] ?? raw['description'] ?? '';
      _logoUrl = b.logoUrl ?? raw['logo_url'] ?? extra['logo_url'];

      // Section 02: Address & Contact
      _addressLine1Ctrl.text = extra['address_line1'] ?? raw['address_line1'] ?? b.location;
      _addressLine2Ctrl.text = extra['address_line2'] ?? raw['address_line2'] ?? '';
      _cityCtrl.text = extra['city'] ?? raw['city'] ?? b.city;
      _stateCtrl.text = extra['state'] ?? raw['state'] ?? _stateCtrl.text;
      _pinCodeCtrl.text = extra['pin_code']?.toString() ?? raw['pin_code']?.toString() ?? '';
      _countryCtrl.text = extra['country'] ?? raw['country'] ?? _countryCtrl.text;
      _phoneCtrl.text = b.contact.replaceAll('+91 ', '').trim();
      _emailCtrl.text = extra['email'] ?? raw['email'] ?? '';
      _latLngCtrl.text = extra['lat_lng'] ?? raw['lat_lng'] ?? '';

